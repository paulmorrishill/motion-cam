/**
 * End-to-end contract test between the standalone HTML generator (tools/qr-config.html,
 * which encodes with the Kazuhiko Arase qrcode-generator library) and the on-device
 * decode path ([QrScanner] -> [SettingsCodec], which uses ZXing).
 *
 * [MATRIX] is the exact QR module grid the HTML page produces for [PAYLOAD] (captured
 * from the page's qrcode.isDark()). We render it to a luma plane with a quiet zone and
 * confirm ZXing reads it back — i.e. a code generated by the web tool is decodable by
 * the phone. If the payload shape or the generator library ever drifts, this fails.
 */
class HtmlGeneratorInteropTest {

    @Test
    fun qrFromHtmlGenerator_decodesOnDevice() {
        val luma = renderMatrixToLuma(MATRIX, scale = 4, marginModules = 4)
        val side = lumaSide(MATRIX, scale = 4, marginModules = 4)

        val decoded = QrScanner().decode(luma, width = side, height = side, rowStride = side)

        assertThat(decoded).isEqualTo(PAYLOAD)
    }

    @Test
    fun decodedPayload_parsesToExpectedSettings() {
        val luma = renderMatrixToLuma(MATRIX, scale = 4, marginModules = 4)
        val side = lumaSide(MATRIX, scale = 4, marginModules = 4)
        val text = QrScanner().decode(luma, side, side, side)!!

        val s = SettingsCodec.decode(text, Settings())

        assertThat(s.deviceName).isEqualTo("garage")
        assertThat(s.ftpHost).isEqualTo("192.168.1.50")
        assertThat(s.ftpPort).isEqualTo(2121)
        assertThat(s.resolutionWidth).isEqualTo(3840)
        assertThat(s.retentionDays).isEqualTo(14)
    }

    private fun lumaSide(matrix: String, scale: Int, marginModules: Int): Int {
        val n = matrix.trim().lines().size
        return (n + 2 * marginModules) * scale
    }

    /** Dark module ('1') -> 0 (black); light ('0') and the quiet-zone margin -> 255. */
    private fun renderMatrixToLuma(matrix: String, scale: Int, marginModules: Int): ByteArray {
        val rows = matrix.trim().lines()
        val n = rows.size
        val side = (n + 2 * marginModules) * scale
        val luma = ByteArray(side * side) { 255.toByte() }
        val off = marginModules * scale
        for (r in 0 until n) {
            for (c in 0 until n) {
                if (rows[r][c] == '1') {
                    val x0 = off + c * scale
                    val y0 = off + r * scale
                    for (dy in 0 until scale) {
                        val base = (y0 + dy) * side + x0
                        for (dx in 0 until scale) luma[base + dx] = 0
                    }
                }
            }
        }
        return luma
    }

